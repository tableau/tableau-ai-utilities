import fs from 'node:fs';
import path from 'node:path';
import type {SidebarsConfig} from '@docusaurus/plugin-content-docs';

const REPO_ROOT = path.resolve(__dirname, '..');

function walkSkillMd(dir: string): boolean {
  if (!fs.existsSync(dir)) return false;
  for (const entry of fs.readdirSync(dir, {withFileTypes: true})) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory() && walkSkillMd(full)) return true;
    if (entry.isFile() && entry.name === 'SKILL.md') return true;
  }
  return false;
}

function hasPlugins(): boolean {
  const marketplacePath = path.join(REPO_ROOT, 'plugins', '.claude-plugin', 'marketplace.json');
  if (!fs.existsSync(marketplacePath)) return false;
  try {
    const marketplace = JSON.parse(fs.readFileSync(marketplacePath, 'utf8')) as {
      plugins?: {name: string; source: string}[];
    };
    if (!marketplace.plugins?.length) return false;
    return marketplace.plugins.some((p) =>
      fs.existsSync(
        path.resolve(path.join(REPO_ROOT, 'plugins'), p.source, '.claude-plugin', 'plugin.json'),
      ),
    );
  } catch {
    return false;
  }
}

const showStudio = walkSkillMd(path.join(REPO_ROOT, 'tableau-studio-skills'));
const showMcp = walkSkillMd(path.join(REPO_ROOT, 'tableau-mcp-skills'));
const showPlugins = hasPlugins();

const sidebars: SidebarsConfig = {
  docsSidebar: [
    'overview',
    'skills',
    ...(showStudio
      ? [
          {
            type: 'category' as const,
            label: 'Tableau Studio Skills',
            className: 'sidebar-installable-skills',
            collapsed: false,
            items: [{type: 'autogenerated' as const, dirName: 'tableau-studio-skills'}],
          },
        ]
      : []),
    ...(showMcp
      ? [
          {
            type: 'category' as const,
            label: 'Tableau MCP Skills',
            className: 'sidebar-installable-skills',
            collapsed: false,
            items: [{type: 'autogenerated' as const, dirName: 'tableau-mcp-skills'}],
          },
        ]
      : []),
    ...(showPlugins
      ? [
          {
            type: 'category' as const,
            label: 'Plugins',
            collapsed: false,
            link: {type: 'doc' as const, id: 'plugins/index'},
            items: [{type: 'autogenerated' as const, dirName: 'plugins'}],
          },
        ]
      : []),
  ],
};

export default sidebars;
